<?php

namespace App\Filament\Resources\WeeklyAllowanceBatchResource\Pages;

use App\Exports\WeeklyAllowanceExport;
use App\Filament\Resources\WeeklyAllowanceBatchResource;
use App\Models\Hris\WeeklyAllowanceBatch;
use App\Services\Hris\WeeklyAllowanceService;
use Filament\Actions;
use Filament\Infolists\Components\Section;
use Filament\Infolists\Components\TextEntry;
use Filament\Infolists\Infolist;
use Filament\Notifications\Notification;
use Filament\Resources\Pages\ViewRecord;
use Maatwebsite\Excel\Facades\Excel;

class ViewWeeklyAllowanceBatch extends ViewRecord
{
    protected static string $resource = WeeklyAllowanceBatchResource::class;

    public function infolist(Infolist $infolist): Infolist
    {
        return $infolist
            ->schema([
                Section::make('Batch Information')
                    ->schema([
                        TextEntry::make('week_label')
                            ->label('Week Period'),
                        TextEntry::make('payment_date')
                            ->date(),
                        TextEntry::make('status')
                            ->badge()
                            ->color(fn (string $state): string => WeeklyAllowanceBatch::getStatusColors()[$state] ?? 'gray'),
                    ])->columns(3),

                Section::make('Summary')
                    ->schema([
                        TextEntry::make('total_employees')
                            ->label('Total Employees'),
                        TextEntry::make('employees_with_warnings')
                            ->label('Employees with Warnings')
                            ->color('danger'),
                        TextEntry::make('total_amount')
                            ->label('Total Amount')
                            ->money('IDR'),
                    ])->columns(3),

                Section::make('Approval Timeline')
                    ->schema([
                        TextEntry::make('generatedBy.name')
                            ->label('Generated By'),
                        TextEntry::make('generated_at')
                            ->label('Generated At')
                            ->dateTime(),
                        TextEntry::make('hrReviewedBy.name')
                            ->label('HR Reviewed By'),
                        TextEntry::make('hr_reviewed_at')
                            ->label('HR Reviewed At')
                            ->dateTime(),
                        TextEntry::make('financeApprovedBy.name')
                            ->label('Finance Approved By'),
                        TextEntry::make('finance_approved_at')
                            ->label('Finance Approved At')
                            ->dateTime(),
                        TextEntry::make('finalApprovedBy.name')
                            ->label('Final Approved By'),
                        TextEntry::make('final_approved_at')
                            ->label('Final Approved At')
                            ->dateTime(),
                        TextEntry::make('paidBy.name')
                            ->label('Paid By'),
                        TextEntry::make('paid_at')
                            ->label('Paid At')
                            ->dateTime(),
                    ])->columns(2),

                Section::make('Notes')
                    ->schema([
                        TextEntry::make('notes')
                            ->label('Notes')
                            ->default('-'),
                        TextEntry::make('rejection_reason')
                            ->label('Rejection Reason')
                            ->visible(fn ($record) => !empty($record->rejection_reason)),
                    ]),
            ]);
    }

    protected function getHeaderActions(): array
    {
        return [
            // HR: Submit to HR
            Actions\Action::make('submit_to_hr')
                ->label('Submit for Review')
                ->icon('heroicon-o-paper-airplane')
                ->color('info')
                ->visible(fn () => $this->record->canSubmitToHr())
                ->requiresConfirmation()
                ->action(function () {
                    $service = app(WeeklyAllowanceService::class);
                    $service->submitToHr($this->record);

                    Notification::make()
                        ->title('Submitted for HR Review')
                        ->success()
                        ->send();

                    $this->refreshFormData(['status']);
                }),

            // HR: Submit to Finance
            Actions\Action::make('submit_to_finance')
                ->label('Submit to Finance')
                ->icon('heroicon-o-banknotes')
                ->color('info')
                ->visible(fn () => $this->record->canSubmitToFinance())
                ->requiresConfirmation()
                ->modalDescription(fn () => $this->record->employees_with_warnings > 0
                    ? "Warning: {$this->record->employees_with_warnings} employee(s) have missing bank information."
                    : 'Submit this batch to Finance for approval?')
                ->action(function () {
                    try {
                        $service = app(WeeklyAllowanceService::class);
                        $service->submitToFinance($this->record);

                        Notification::make()
                            ->title('Submitted to Finance')
                            ->success()
                            ->send();

                        $this->refreshFormData(['status']);
                    } catch (\Exception $e) {
                        Notification::make()
                            ->title('Cannot Submit')
                            ->body($e->getMessage())
                            ->danger()
                            ->send();
                    }
                }),

            // Finance: Approve
            Actions\Action::make('approve_finance')
                ->label('Finance Approve')
                ->icon('heroicon-o-check-circle')
                ->color('warning')
                ->visible(fn () => $this->record->canApproveByFinance())
                ->requiresConfirmation()
                ->action(function () {
                    $service = app(WeeklyAllowanceService::class);
                    $service->approveByFinance($this->record);

                    Notification::make()
                        ->title('Approved by Finance')
                        ->success()
                        ->send();

                    $this->refreshFormData(['status']);
                }),

            // Final: Approve
            Actions\Action::make('approve_final')
                ->label('Final Approve')
                ->icon('heroicon-o-shield-check')
                ->color('success')
                ->visible(fn () => $this->record->canApproveFinal())
                ->requiresConfirmation()
                ->action(function () {
                    $service = app(WeeklyAllowanceService::class);
                    $service->approveFinal($this->record);

                    Notification::make()
                        ->title('Final Approval Complete')
                        ->success()
                        ->send();

                    $this->refreshFormData(['status']);
                }),

            // Mark as Paid
            Actions\Action::make('mark_paid')
                ->label('Mark as Paid')
                ->icon('heroicon-o-banknotes')
                ->color('success')
                ->visible(fn () => $this->record->canMarkAsPaid())
                ->requiresConfirmation()
                ->action(function () {
                    $service = app(WeeklyAllowanceService::class);
                    $service->markAsPaid($this->record);

                    Notification::make()
                        ->title('Marked as Paid')
                        ->success()
                        ->send();

                    $this->refreshFormData(['status']);
                }),

            // Export CSV for bank transfer
            Actions\Action::make('export')
                ->label('Export Bank Transfer')
                ->icon('heroicon-o-arrow-down-tray')
                ->color('gray')
                ->visible(fn () => in_array($this->record->status, [
                    WeeklyAllowanceBatch::STATUS_APPROVED,
                    WeeklyAllowanceBatch::STATUS_PAID,
                ]))
                ->action(function () {
                    $weekLabel = $this->record->week_start_date->format('d') . '-' .
                        $this->record->week_end_date->format('d_M_Y');
                    $filename = "weekly_allowance_{$weekLabel}.xlsx";

                    return Excel::download(
                        new WeeklyAllowanceExport($this->record),
                        $filename
                    );
                }),

            Actions\EditAction::make()
                ->visible(fn () => $this->record->isEditable()),
        ];
    }
}
