<?php

namespace App\Services\Hris;

use App\Models\Hris\FinanceAttachment;
use App\Models\User;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;

/**
 * Stores, hashes, dedup-flags, locks and deletes finance attachments on the private disk.
 * No public URLs are ever produced; downloads are authorized at the controller/policy layer.
 */
class FinanceAttachmentService
{
    private const DISK = 'private';

    public function __construct(private FinanceAuditLogger $audit) {}

    public function store(Model $attachable, UploadedFile $file, string $role, User $uploader): FinanceAttachment
    {
        $hash = hash_file('sha256', $file->getRealPath());
        $size = $file->getSize();
        $mime = $file->getClientMimeType();
        $originalName = $file->getClientOriginalName();

        $duplicateIds = FinanceAttachment::where('file_hash', $hash)->pluck('id')->all();

        $path = $file->store("finance-attachments/{$role}", self::DISK);

        $metadata = [];
        if (! empty($duplicateIds)) {
            $metadata['duplicate_warning'] = true;
            $metadata['duplicate_of'] = array_values($duplicateIds);
        }

        $attachment = FinanceAttachment::create([
            'attachable_type' => get_class($attachable),
            'attachable_id' => $attachable->id,
            'attachment_role' => $role,
            'file_path' => $path,
            'file_hash' => $hash,
            'file_size' => $size,
            'mime_type' => $mime,
            'original_filename' => $originalName,
            'uploaded_by' => $uploader->id,
            'uploaded_at' => now(),
            'metadata' => $metadata ?: null,
        ]);

        $this->audit->log($attachment, 'finance_attachment.uploaded', $uploader, [
            'after' => [
                'attachment_role' => $attachment->attachment_role,
                'file_hash' => $attachment->file_hash,
                'attachable_type' => $attachment->attachable_type,
                'attachable_id' => $attachment->attachable_id,
            ],
        ]);

        return $attachment;
    }

    /**
     * Like store() but for generated byte strings (e.g. DomPDF output) rather than uploaded files.
     */
    public function storeGeneratedFile(Model $attachable, string $contents, string $role, string $filename, string $mime, User $uploader): FinanceAttachment
    {
        $hash = hash('sha256', $contents);
        $ext = pathinfo($filename, PATHINFO_EXTENSION) ?: 'bin';
        $path = "finance-attachments/{$role}/".Str::random(40).'.'.$ext;

        Storage::disk(self::DISK)->put($path, $contents);

        $attachment = FinanceAttachment::create([
            'attachable_type' => get_class($attachable),
            'attachable_id' => $attachable->id,
            'attachment_role' => $role,
            'file_path' => $path,
            'file_hash' => $hash,
            'file_size' => strlen($contents),
            'mime_type' => $mime,
            'original_filename' => $filename,
            'uploaded_by' => $uploader->id,
            'uploaded_at' => now(),
        ]);

        $this->audit->log($attachment, 'finance_attachment.uploaded', $uploader, [
            'after' => [
                'attachment_role' => $attachment->attachment_role,
                'file_hash' => $attachment->file_hash,
                'attachable_type' => $attachment->attachable_type,
                'attachable_id' => $attachment->attachable_id,
            ],
        ]);

        return $attachment;
    }

    /**
     * Lock an attachment (it has become part of a finance verification or COO approval snapshot).
     * Locked files are immutable — replacing one requires re-review/re-approval.
     */
    public function lock(FinanceAttachment $attachment, string $reason, ?User $actor = null): void
    {
        $attachment->update([
            'locked_at' => now(),
            'locked_reason' => $reason,
        ]);

        $this->audit->log($attachment, 'finance_attachment.locked', $actor, ['reason' => $reason]);
    }

    /**
     * Delete an attachment + its file. Locked attachments cannot be silently replaced/removed.
     *
     * @throws \RuntimeException when the attachment is locked.
     */
    public function delete(FinanceAttachment $attachment, ?User $actor = null): void
    {
        if ($attachment->isLocked()) {
            throw new \RuntimeException('Locked finance attachment cannot be deleted or replaced.');
        }

        $id = $attachment->id;
        $role = $attachment->attachment_role;

        Storage::disk(self::DISK)->delete($attachment->file_path);
        $attachment->delete();

        $this->audit->log($attachment, 'finance_attachment.deleted', $actor, [
            'before' => [
                'attachment_id' => $id,
                'attachment_role' => $role,
            ],
        ]);
    }
}
